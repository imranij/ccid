def table_descriptor_correction(path: str):
    """Replacement for the manuscript's Table 12: published vs independently recomputed."""
    with open(os.path.join(RESULTS, "a4_descriptor_forensics.json")) as fh:
        fo = json.load(fh)
    scr = pd.read_csv(os.path.join(RESULTS, "a4_descriptor_screen_all_candidates.csv"))
    from pymatgen.core import Composition
    pub = json.load(open(_CCID_ROOT + "/dgx/outputs_dgx/"
                         "candidate_stability_assessment.json"))

    rows = []
    for p in pub:
        f = p["formula"]
        red = Composition(f).reduced_formula
        m = scr[scr["formula"] == red]
        if m.empty:
            t_new, dchi_new, applic, note = np.nan, np.nan, False, "not in deposited pool"
        else:
            r = m.iloc[0]
            t_new = r["goldschmidt_t"]
            dchi_new = r["electronegativity_diff"]
            applic = bool(r["goldschmidt_applicable"])
            note = "in pool"
        rows.append(dict(formula=f, t_pub=p["goldschmidt_tolerance"], t_new=t_new,
                         dchi_pub=p["electronegativity_diff"], dchi_new=dchi_new,
                         applic=applic, note=note))

    lines = [HEAD, r"\begin{table}[htbp]", r"\centering",
             r"\caption{Independent recomputation of the descriptor screen previously "
             r"reported for six Composition-CVAE candidates. Electronegativity differences "
             r"reproduce exactly under the definition $\Delta\chi = \chi(\mathrm{O}) - "
             r"\langle\chi_{\mathrm{cation}}\rangle$ (cation-count weighted). The previously "
             r"reported Goldschmidt tolerance factors could not be reproduced under any of "
             r"twelve tested definitions; recomputed values use Shannon radii "
             r"($r_A$ at CN\,XII, $r_B$ at CN\,VI, $r_{\mathrm{O}}=1.40$\,\AA) and are given "
             r"only where a perovskite-derived $A$/$B$ site assignment exists. "
             r"``n/a'' marks stoichiometries for which the tolerance factor is undefined.}",
             r"\label{tab:descriptor_correction}",
             r"\begin{tabular}{lccccl}", r"\toprule",
             r"Candidate & $t$ (reported) & $t$ (recomputed) & $\Delta\chi$ (reported) "
             r"& $\Delta\chi$ (recomputed) & Status \\", r"\midrule"]
    for r in rows:
        tn = f"{r['t_new']:.3f}" if np.isfinite(r["t_new"]) else "n/a"
        dn = f"{r['dchi_new']:.3f}" if np.isfinite(r["dchi_new"]) else "---"
        st = "not in deposited pool" if r["note"] != "in pool" else \
             ("perovskite-derived" if r["applic"] else "non-perovskite")
        lines.append(f"{_esc(r['formula'])} & {r['t_pub']:.3f} & {tn} & "
                     f"{r['dchi_pub']:.3f} & {dn} & {st} \\\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]

    # applicability summary
    n_ap = int(scr["goldschmidt_applicable"].sum())
    lines += [
        r"% Applicability of the Goldschmidt tolerance factor across the full pool:",
        f"% defined for {n_ap} of {len(scr)} unique valid candidates.",
        r"% Composite stability score: reproduced to 5e-4 by "
        f"score = {fo['composite_lstsq_on_t_and_dchi']['intercept']:.4f} "
        f"+ {fo['composite_lstsq_on_t_and_dchi']['coef_t']:.4f} t "
        f"+ {fo['composite_lstsq_on_t_and_dchi']['coef_dchi']:.4f} dchi "
        f"(R^2 = {fo['composite_lstsq_on_t_and_dchi']['r2']:.4f}); no deposited code defines it.",
    ]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))
    return rows


