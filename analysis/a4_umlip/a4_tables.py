def table_full_screen(path: str):
    """Supplementary long table: descriptor screen over all unique valid candidates."""
    scr = pd.read_csv(os.path.join(RESULTS, "a4_descriptor_screen_all_candidates.csv"))
    lines = [HEAD, r"\begin{longtable}{lccccl}",
             r"\caption{Descriptor screen extended to all unique valid Composition-CVAE "
             r"candidates, as requested by the reviewers. $t$ is reported only where a "
             r"perovskite-derived site assignment exists. The final column records whether "
             r"the composition can be charge-balanced using only the standard closed-shell "
             r"oxidation state of every cation, or whether it requires a reduced, open-shell "
             r"cation (Ti$^{3+}$ or Sn$^{2+}$) that is inconsistent with a wide-gap dielectric "
             r"target.}\label{tab:full_descriptor_screen}\\", r"\toprule",
             r"Candidate & $n_{\mathrm{cat}}$ & $n_{\mathrm{O}}$ & $t$ & $\Delta\chi$ "
             r"& Charge balance \\", r"\midrule", r"\endfirsthead",
             r"\toprule Candidate & $n_{\mathrm{cat}}$ & $n_{\mathrm{O}}$ & $t$ & $\Delta\chi$ "
             r"& Charge balance \\ \midrule \endhead",
             r"\bottomrule \endfoot"]
    for _, r in scr.sort_values("formula").iterrows():
        t = f"{r['goldschmidt_t']:.3f}" if r["goldschmidt_applicable"] else "n/a"
        cb = "standard states" if r["requires_reduced_cation"] == False else \
             ("requires " + str(r["redox_note"]).split(": ")[-1]
              if r["requires_reduced_cation"] == True else "---")
        lines.append(f"{_esc(str(r['formula']))} & {int(r['n_cations'])} & {int(r['n_oxygen'])} "
                     f"& {t} & {r['electronegativity_diff']:.3f} & {cb} \\\\")
    lines += [r"\end{longtable}", ""]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


if __name__ == "__main__":
    table_descriptor_correction(os.path.join(RESULTS, "a4_table_descriptor_correction.tex"))
    table_full_screen(os.path.join(RESULTS, "a4_table_full_descriptor_screen.tex"))
    table_energetics(os.path.join(RESULTS, "a4_table_umlip_energetics.tex"))
    print("tables written")
