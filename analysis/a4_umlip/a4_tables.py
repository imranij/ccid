"""
a4_tables.py -- booktabs LaTeX tables for the revision.

Every number written here is read from a file produced by a script in this directory.
Nothing is typed in by hand except the PUBLISHED column, which is read verbatim from
dgx/outputs_dgx/candidate_stability_assessment.json for side-by-side comparison.
"""
from __future__ import annotations

import os as _os, pathlib as _pl
_CCID_ROOT = _os.environ.get("CCID_ROOT") or str(_pl.Path(__file__).resolve().parents[2])  # repo root
import json
import os
import warnings

import numpy as np
import pandas as pd

warnings.filterwarnings("ignore")
RESULTS = _CCID_ROOT + "/results"

HEAD = r"""% Generated by a4_tables.py -- do not edit by hand.
% Requires \usepackage{booktabs} and \usepackage{siunitx} (or drop the S column types).
"""


def _sg(s: str) -> str:
    """Render a Hermann-Mauguin symbol safely for LaTeX.

    Space group strings contain bare underscores (P2_1/c) and bars (Fm-3m) that would
    otherwise break compilation or typeset wrongly. Screw-axis subscripts become real
    subscripts and the inversion bar becomes \\bar."""
    s = str(s)
    out, i = "", 0
    while i < len(s):
        if s[i] == "_" and i + 1 < len(s):
            out += "$_{" + s[i + 1] + "}$"
            i += 2
        elif s[i] == "-" and i + 1 < len(s) and s[i + 1].isdigit():
            out += "$\\bar{" + s[i + 1] + "}$"
            i += 2
        else:
            out += s[i]
            i += 1
    return out


def _esc(f: str) -> str:
    """Render a chemical formula with LaTeX subscripts."""
    out, i = "", 0
    while i < len(f):
        if f[i].isdigit():
            j = i
            while j < len(f) and f[j].isdigit():
                j += 1
            out += "$_{" + f[i:j] + "}$"
            i = j
        else:
            out += f[i]
            i += 1
    return out


