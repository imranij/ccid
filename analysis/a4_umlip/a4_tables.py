def table_energetics(path: str, top: int = 20):
    f_ch = os.path.join(RESULTS, "a4_energetics_chgnet.csv")
    if not os.path.exists(f_ch):
        return
    ch = pd.read_csv(f_ch)
    mc_path = os.path.join(RESULTS, "a4_energetics_mace.csv")
    mc = pd.read_csv(mc_path) if os.path.exists(mc_path) else None
    if mc is not None:
        ch = ch.merge(mc[["formula", "decomposition_energy_eV_per_atom",
                          "relaxed_spacegroup"]],
                      on="formula", how="left", suffixes=("", "_mace"))

    d = ch.sort_values("decomposition_energy_eV_per_atom", na_position="last").head(top)
    has_mace = mc is not None
    cols = "llcc" + ("c" if has_mace else "")
    lines = [HEAD, r"\begin{table}[htbp]", r"\centering", r"\small",
             r"\caption{Universal machine-learned interatomic potential energetics for "
             r"Composition-CVAE candidates. Each candidate's structure is the lowest-energy "
             r"member of a bounded set of trial structures (stoichiometry-matched prototype "
             r"substitutions plus random symmetric structures), fully relaxed in cell and "
             r"ions. $\Delta E_{\mathrm{dec}}$ is the energy of decomposition into the "
             r"constituent binary oxides, with candidate and references relaxed by the same "
             r"potential. Negative $\Delta E_{\mathrm{dec}}$ indicates stability against that "
             r"decomposition; positive values are inconclusive, since the trial-structure set "
             r"is finite and provides only an upper bound on the ground-state energy. These "
             r"are not energies above the convex hull.}",
             r"\label{tab:umlip_energetics}",
             rf"\begin{{tabular}}{{{cols}}}", r"\toprule"]
    hdr = (r"Candidate & Best trial structure & Space group & "
           r"$\Delta E_{\mathrm{dec}}$ (CHGNet) ")
    if has_mace:
        hdr += r"& $\Delta E_{\mathrm{dec}}$ (MACE) "
    lines += [hdr + r"\\",
              r" & & (relaxed) & (eV/atom) " + (r"& (eV/atom) " if has_mace else "") + r"\\",
              r"\midrule"]
    for _, r in d.iterrows():
        de = r["decomposition_energy_eV_per_atom"]
        s = f"{de:+.3f}" if np.isfinite(de) else "---"
        proto = str(r["best_prototype"]).replace("_", r"\_")
        line = (f"{_esc(str(r['formula']))} & \\texttt{{{proto}}} & "
                f"{_sg(r['relaxed_spacegroup'])} & {s} ")
        if has_mace:
            dm = r.get("decomposition_energy_eV_per_atom_mace", np.nan)
            line += f"& {dm:+.3f} " if np.isfinite(dm) else "& --- "
        lines.append(line + r"\\")
    lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
    with open(path, "w") as fh:
        fh.write("\n".join(lines))


